#!/usr/bin/env python3
# gen_vectors.py - builds src/eq_vectors.h from Kerrigan's reference solutions
# (kref_test = Kerrigan's own Equihash code + libsodium, cloud only) and the exact
# level counts of the CPU emulation (eq_cloud_test).  BLAKE2b known answers are
# computed with Python's hashlib (independent implementation).
import hashlib, subprocess, sys, struct, re
vec_files, cloud_test, out = sys.argv[1], sys.argv[2], sys.argv[3]
vecs = []
for line in open(vec_files):
    line = line.strip()
    if line.startswith('H '): vecs.append([line[2:], []])
    elif line.startswith('V '): vecs[-1][1].append(line[2:])
    elif line.startswith('X '): sys.exit('invalid reference solution in input')
res = []
for h, sols in vecs:
    r = subprocess.run([cloud_test, h] + sols, capture_output=True, text=True)
    sys.stderr.write(r.stdout)
    m = re.search(r'level counts: (.*), (\d+) candidates', r.stdout)
    counts = [int(x.split('(')[0]) for x in m.group(1).split()]
    drops = [int(x.split('(-')[1].rstrip(')')) for x in m.group(1).split()]
    if 'RESULT OK' not in r.stdout or '0 missing, 0 extra' not in r.stdout or any(drops):
        sys.exit('emulation does not match the reference for ' + h[:40])
    res.append((h, sols, counts))
person = b'kerrigan' + struct.pack('<II', 192, 7)
kat = []
for vi, (h, _, _) in enumerate(res[:2]):
    hb = bytes.fromhex(h)
    for g in (0, 1, 777, 0xabcdef, (1 << 24) - 1):
        d = hashlib.blake2b(hb + struct.pack('<I', g), digest_size=48, person=person).hexdigest()
        kat.append((vi, g, d))
with open(out, 'w') as f:
    f.write('// eq_vectors.h - generated by tools/gen_vectors.py: Equihash(192,7) "kerrigan" headers\n'
            '// (real rplant job, varied nonces) with the solutions of Kerrigan\'s own solver and the\n'
            '// exact string count of every level (CPU emulation of the GPU solver).  Apache-2.0.\n#pragma once\n#include <stdint.h>\n\n')
    f.write('struct EqVector { const char* header_hex; int nsols; const char* sols[8]; uint32_t level_counts[7]; };\n')
    f.write('struct EqBlakeKat { int vector; uint32_t g; const char* digest_hex; };\n\n')
    f.write('static const EqVector eq_vectors[] = {\n')
    for h, sols, counts in res:
        f.write('    { "%s",\n      %d, {\n' % (h, len(sols)))
        for s in sols: f.write('        "%s",\n' % s)
        f.write('      }, { %s } },\n' % ', '.join('%du' % c for c in counts))
    f.write('};\n\nstatic const EqBlakeKat eq_blake_kat[] = {\n')
    for vi, g, d in kat: f.write('    { %d, 0x%06xu, "%s" },\n' % (vi, g, d))
    f.write('};\n')
print('vectors:', len(res), 'solutions:', sum(len(s) for _, s, _ in res))
